#!/usr/bin/env bash

set -ouex pipefail

###############################################################################
# Copiar archivos personalizados
###############################################################################

cp -avf /ctx/system_files/. /

###############################################################################
# Actualizar el sistema
###############################################################################

dnf5 -y upgrade

###############################################################################
# Instalar XFCE
###############################################################################

dnf5 install -y \
    xfce4-panel \
    xfce4-session \
    xfce4-settings \
    xfdesktop \
    xfwm4 \
    thunar \
    thunar-volman \
    xfce4-appfinder \
    xfce4-power-manager \
    xfce4-terminal \
    xfce4-screenshooter \
    xfce4-taskmanager \
    xfce4-notifyd \
    xfce4-pulseaudio-plugin \
    xfce4-clipman-plugin \
    xfce4-whiskermenu-plugin \
    xfce4-weather-plugin

###############################################################################
# Gestor de inicio de sesión
###############################################################################

dnf5 install -y \
    lightdm \
    lightdm-gtk

###############################################################################
# Apariencia
###############################################################################

dnf5 install -y \
    papirus-icon-theme \
    adwaita-gtk3-theme

###############################################################################
# Utilidades básicas
###############################################################################

dnf5 install -y \
    fastfetch \
    git \
    curl \
    wget \
    unzip \
    zip \
    tar \
    nano \
    vim \
    htop \
    btop \
    tree \
    rsync

###############################################################################
# Red
###############################################################################

dnf5 install -y \
    NetworkManager \
    NetworkManager-wifi

###############################################################################
# Compresión
###############################################################################

dnf5 install -y \
    file-roller \
    p7zip \
    unrar

###############################################################################
# Habilitar servicios
###############################################################################

systemctl enable NetworkManager.service
systemctl enable lightdm.service

###############################################################################
# Limpiar caché
###############################################################################

dnf5 clean all
