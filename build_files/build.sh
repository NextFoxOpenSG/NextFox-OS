#!/usr/bin/env bash

set -ouex pipefail

###############################################################################
# Copiar archivos personalizados
###############################################################################

cp -avf /ctx/system_files/. /

###############################################################################
# Actualizar sistema
###############################################################################

dnf5 -y upgrade

###############################################################################
# Escritorio XFCE
###############################################################################

dnf5 install -y \
    xfce4-panel \
    xfce4-session \
    xfce4-settings \
    xfdesktop \
    xfwm4 \
    thunar \
    thunar-volman \
    xfce4-appfinder \
    xfce4-power-manager \
    xfce4-terminal \
    xfce4-screenshooter \
    xfce4-taskmanager \
    xfce4-notifyd \
    xfce4-pulseaudio-plugin \
    xfce4-clipman-plugin \
    xfce4-whiskermenu-plugin \
    xfce4-weather-plugin

###############################################################################
# Display Manager
###############################################################################

dnf5 install -y \
    lightdm \
    lightdm-gtk-greeter

###############################################################################
# Audio
###############################################################################

dnf5 install -y \
    pipewire \
    pipewire-alsa \
    pipewire-pulseaudio \
    pipewire-utils \
    wireplumber

###############################################################################
# Flatpak
###############################################################################

dnf5 install -y \
    flatpak

###############################################################################
# Portales XDG
###############################################################################

dnf5 install -y \
    xdg-desktop-portal \
    xdg-desktop-portal-gtk

###############################################################################
# Bluetooth
###############################################################################

dnf5 install -y \
    bluez \
    bluez-tools

###############################################################################
# Impresión
###############################################################################

dnf5 install -y \
    cups \
    cups-client

###############################################################################
# Red
###############################################################################

dnf5 install -y \
    NetworkManager \
    NetworkManager-wifi

###############################################################################
# Apariencia
###############################################################################

dnf5 install -y \
    papirus-icon-theme \
    adwaita-gtk3-theme

###############################################################################
# Compresión
###############################################################################

dnf5 install -y \
    file-roller \
    p7zip \
    unrar

###############################################################################
# Utilidades
###############################################################################

dnf5 install -y \
    fastfetch \
    git \
    curl \
    wget \
    unzip \
    zip \
    tar \
    nano \
    vim \
    htop \
    btop \
    tree \
    rsync

###############################################################################
# Habilitar servicios
###############################################################################

systemctl enable NetworkManager.service
systemctl enable lightdm.service
systemctl enable bluetooth.service
systemctl enable cups.service

###############################################################################
# Habilitar Flathub
###############################################################################

flatpak remote-add --if-not-exists flathub \
https://dl.flathub.org/repo/flathub.flatpakrepo

###############################################################################
# Fastfetch
###############################################################################
# Copia tu configuración a:
#
# system_files/etc/xdg/fastfetch/config.jsonc
#
# y tu logo ASCII a:
#
# system_files/usr/share/nextfox/fastfetch/logo.txt
#

###############################################################################
# Wallpapers
###############################################################################
# Guarda tus wallpapers en:
#
# system_files/usr/share/backgrounds/NextFoxOS/
#

###############################################################################
# Papirus personalizado
###############################################################################
# Si personalizas Papirus, colócalo en:
#
# system_files/usr/share/icons/Papirus-NextFox/
#

###############################################################################
# Limpieza
###############################################################################

dnf5 clean all
